number = "42"               # Store the string "42" in the variable 'number'

print(number)               # Print the string value "42"

print(type(number))         # Display the data type of 'number' (it will be <class 'str'>)

int_number = int(number)    # Convert the string "42" into an integer and store it in 'int_number'

print(int_number)           # Print the integer value 42

print(type(int_number))     # Display the data type of 'int_number' (it will be <class 'int'>)

print(int_number + 5)       # Integer addition: 42 + 5 = 47

print(number + "5")         # String concatenation: "42" + "5" = "425"
